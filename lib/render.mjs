// Turn the analysis into a CLAUDE.md.
//
// The guiding rule: every line is something an assistant could not work out
// faster by looking, or would get wrong by guessing. No filler sections, and
// nothing asserted that the analysis did not observe.

const GROUP_ORDER = ["run", "build", "test", "check", "database", "deploy", "other"];
const GROUP_TITLE = {
  run: "Run it",
  build: "Build",
  test: "Test",
  check: "Lint and types",
  database: "Database",
  deploy: "Deploy",
  other: "Other scripts",
};

export function render(a, { withEvidence = false } = {}) {
  const L = [];
  const ev = (text) => (withEvidence ? `  <!-- ${text} -->` : "");

  L.push(`# ${a.name}`, "");
  if (a.description) L.push(a.description, "");

  // --- What this is
  const langs = a.languages.slice(0, 3).map((l) => `${l.name} (${l.share}%)`);
  const tools = a.stack.map((s) => s.name);
  if (langs.length || tools.length) {
    L.push("## What this is", "");
    if (langs.length) L.push(`- **Language:** ${langs.join(", ")}`);
    if (tools.length) L.push(`- **Stack:** ${tools.slice(0, 14).join(", ")}`);
    if (a.packageManager) {
      L.push(`- **Package manager:** ${a.packageManager.name} — use it, not another one`);
      if (withEvidence) L.push(ev(a.packageManager.evidence));
    }
    L.push(`- **Size:** ${a.fileCount}${a.truncated ? "+" : ""} files`);
    L.push("");
  }

  // --- Commands
  const groups = new Map();
  for (const s of a.scripts) {
    if (!groups.has(s.kind)) groups.set(s.kind, []);
    groups.get(s.kind).push(s);
  }
  const shown = GROUP_ORDER.filter((g) => groups.has(g) && g !== "other");
  if (shown.length) {
    L.push("## Commands", "");
    for (const g of shown) {
      L.push(`**${GROUP_TITLE[g]}**`, "");
      for (const s of groups.get(g)) L.push(`- \`${s.command}\`${s.raw ? ` — ${trim(s.raw)}` : ""}`);
      L.push("");
    }
  }

  // --- Layout
  if (a.layout.length) {
    L.push("## Layout", "");
    for (const d of a.layout) L.push(`- \`${d.path}/\` — ${d.files} files`);
    L.push("");
  }

  // --- Entry points
  if (a.entryPoints.length) {
    L.push("## Start reading here", "");
    for (const e of a.entryPoints) L.push(`- \`${e.path}\`${withEvidence ? ` (${e.why})` : ""}`);
    L.push("");
  }

  // --- Conventions
  if (a.conventions.length) {
    L.push("## Conventions", "");
    for (const c of a.conventions) L.push(`- ${c.text}${withEvidence ? ev(c.evidence) : ""}`);
    L.push("");
  }

  // --- Git
  if (a.git) {
    L.push("## Git", "");
    if (a.git.branch) L.push(`- Default working branch when generated: \`${a.git.branch}\``);
    if (a.git.remote) L.push(`- Remote: ${a.git.remote}`);
    if (a.git.conventional >= 60) {
      L.push(`- Commit messages follow conventional commits (${a.git.conventional}% of the last ${a.git.commits})`);
    } else if (a.git.commits) {
      L.push(`- Commit messages are plain prose, not conventional commits (${a.git.conventional}% of the last ${a.git.commits})`);
    }
    L.push("");
  }

  // --- Environment
  if (a.env && a.env.names.length) {
    L.push("## Environment", "");
    L.push(`Required variables, from \`${a.env.file}\`:`, "");
    L.push(a.env.names.map((n) => `\`${n}\``).join(" · "), "");
    L.push("Never read or print the real values from a local env file.", "");
  }

  // --- Docs
  if (a.docs.length) {
    L.push("## Further reading", "");
    for (const d of a.docs) L.push(`- [\`${d}\`](${d})`);
    L.push("");
  }

  L.push("---", "");
  L.push(
    "<!-- Generated by claudemd-init from what is on disk. Everything above was",
    "     observed, not inferred. Add the things a tool cannot see: why the odd",
    "     decisions were made, what is deliberately not done, and what to ask",
    "     about before changing. -->",
    ""
  );

  return L.filter((l) => l !== "").length ? L.join("\n").replace(/\n{3,}/g, "\n\n") : "";
}

function trim(s, n = 70) {
  const one = String(s).replace(/\s+/g, " ").trim();
  return one.length > n ? one.slice(0, n - 1) + "…" : one;
}

/** A short terminal summary of what was found. */
export function summarise(a) {
  const bits = [];
  bits.push(`${a.fileCount}${a.truncated ? "+" : ""} files`);
  if (a.languages.length) bits.push(a.languages[0].name);
  if (a.stack.length) bits.push(`${a.stack.length} tools`);
  if (a.scripts.length) bits.push(`${a.scripts.length} scripts`);
  if (a.git) bits.push("git");
  return bits.join(" · ");
}
